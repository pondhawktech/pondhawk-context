using System.Text;
using Pondhawk.Context.Generator.Models;

namespace Pondhawk.Context.Generator.Emitters;

/// <summary>
/// Turns an <see cref="AmbientContextModel"/> into the generated source: the partial
/// interface that carries its own implementation, and the stateless singleton behind it.
/// </summary>
internal static class AmbientContextEmitter
{
    private const string GeneratorName = "Pondhawk.Context.Generator";
    private const string GeneratorVersion = "1.0.0";
    private const string InstanceInterface = "global::Pondhawk.Context.IAmbientContextInstance";
    private const string ContextApi = "global::Pondhawk.Context.AmbientContext";

    public static string Emit(AmbientContextModel model)
    {
        var builder = new StringBuilder();
        var indent = string.Empty;

        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();

        if (model.ContainingNamespace is not null)
        {
            builder.Append("namespace ").AppendLine(model.ContainingNamespace);
            builder.AppendLine("{");
            indent = "    ";
        }

        EmitInterfacePart(builder, indent, model);
        builder.AppendLine();
        EmitImplementation(builder, indent, model);

        if (model.ContainingNamespace is not null)
            builder.AppendLine("}");

        return builder.ToString();
    }

    /// <summary>
    /// Emits the half of the partial interface that satisfies the
    /// <c>IAmbientContextInstance&lt;TSelf&gt;</c> constraint. This is what lets
    /// <c>Ambient&lt;T&gt;.Current</c> resolve with a direct static call instead of a
    /// runtime registry.
    /// </summary>
    private static void EmitInterfacePart(StringBuilder builder, string indent, AmbientContextModel model)
    {
        var self = model.QualifiedInterfaceName;

        builder
            .Append(indent).Append(model.Accessibility).Append(" partial interface ").Append(model.InterfaceName)
            .Append(" : ").Append(InstanceInterface).Append('<').Append(self).AppendLine(">");
        builder.Append(indent).AppendLine("{");

        builder
            .Append(indent).Append("    static ").Append(self).Append(' ')
            .Append(InstanceInterface).Append('<').Append(self).AppendLine(">.Instance");
        builder
            .Append(indent).Append("        => ").Append(model.ImplementationName).AppendLine(".Instance;");

        builder.Append(indent).AppendLine("}");
    }

    private static void EmitImplementation(StringBuilder builder, string indent, AmbientContextModel model)
    {
        builder
            .Append(indent).Append("[global::System.CodeDom.Compiler.GeneratedCode(\"")
            .Append(GeneratorName).Append("\", \"").Append(GeneratorVersion).AppendLine("\")]");
        builder
            .Append(indent).AppendLine("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        builder
            .Append(indent).Append("internal sealed class ").Append(model.ImplementationName)
            .Append(" : ").AppendLine(model.QualifiedInterfaceName);
        builder.Append(indent).AppendLine("{");

        // A single shared instance is safe: the implementation holds no request state,
        // every accessor goes to the active provider.
        builder
            .Append(indent).Append("    internal static readonly ").Append(model.QualifiedInterfaceName)
            .Append(" Instance = new ").Append(model.ImplementationName).AppendLine("();");
        builder.AppendLine();
        builder.Append(indent).Append("    private ").Append(model.ImplementationName).AppendLine("()");
        builder.Append(indent).AppendLine("    {");
        builder.Append(indent).AppendLine("    }");

        foreach (var property in model.Properties)
        {
            builder.AppendLine();
            EmitProperty(builder, indent, property);
        }

        builder.Append(indent).AppendLine("}");
    }

    private static void EmitProperty(StringBuilder builder, string indent, AmbientPropertyModel property)
    {
        builder
            .Append(indent).Append("    public ").Append(property.DeclaredType).Append(' ')
            .AppendLine(property.Name);
        builder.Append(indent).AppendLine("    {");

        if (property.HasGetter)
        {
            builder
                .Append(indent).Append("        get => ").Append(ContextApi).Append(".Get<")
                .Append(property.StorageType).Append(">(nameof(").Append(property.Name).Append("))")
                .Append(property.SuppressNullWarning ? "!" : string.Empty).AppendLine(";");
        }

        if (property.HasSetter)
        {
            builder
                .Append(indent).Append("        set => ").Append(ContextApi).Append(".Set(nameof(")
                .Append(property.Name).AppendLine("), value);");
        }

        builder.Append(indent).AppendLine("    }");
    }
}
